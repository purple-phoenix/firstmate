# shellcheck shell=bash
# Watcher check-cadence constants, shared by every process that has to LOCATE or
# GENERATE the cadence file. Deliberately dependency-free and side-effect-free:
# the cadence owner loads it without loading the watcher graph.
# Usage: . bin/fm-cadence-lib.sh
#
# bin/fm-cadence.sh owns the contract itself - when the file exists, what arms it,
# and what a transition means. This file only says what it is called and what it
# contains, so no consumer has to hard-code either.

# Presence of this file in a home's config dir means "poll checks fast".
FM_CADENCE_BASENAME=check-cadence.env
FM_CADENCE_FAST_SECS=30
# The pre-rename path, generated by firstmate versions where only X mode had a
# fast cadence. bin/fm-cadence.sh removes it on reconcile.
FM_CADENCE_LEGACY_BASENAME=x-mode.env

fm_cadence_file() {
  printf '%s/%s\n' "$1" "$FM_CADENCE_BASENAME"
}

fm_cadence_legacy_file() {
  printf '%s/%s\n' "$1" "$FM_CADENCE_LEGACY_BASENAME"
}

# The exact generated content. Byte-identical output here is what lets repeated
# reconciliation leave an existing file untouched.
fm_cadence_body() {
  cat <<EOF
# Auto-generated by bin/fm-cadence.sh - watcher check cadence.
# Present only while this home has an armed inbound captain channel (X mode relay
# polling, the Telegram captain channel, the dashboard channel, or any
# combination). Never source this file;
# bin/fm-cadence.sh validates it and applies the fixed ${FM_CADENCE_FAST_SECS}s
# interval when a watcher starts. A home with no armed channel has no such file
# at all and keeps the default 300s cadence.
export FM_CHECK_INTERVAL=$FM_CADENCE_FAST_SECS
EOF
}
